function taskEvents(taskId: string, status: TaskStatus, updatedAt: string): TaskEvent[] {
  const events: TaskEvent[] = [
    {
      id: `${taskId}-event-created`,
      type: 'created',
      title: '任务已创建',
      description: '需求已拆解为可执行任务，并写入项目队列。',
      createdAt: '8 月 5 日 09:12',
    },
  ]

  if (status !== 'pending') {
    events.push({
      id: `${taskId}-event-assigned`,
      type: status === 'awaiting_approval' ? 'approval' : 'assigned',
      title: status === 'awaiting_approval' ? '执行方案等待审批' : 'Agent 已接收任务',
      description: status === 'awaiting_approval' ? '高影响步骤需要负责人批准后继续。' : '执行资源与项目上下文已完成绑定。',
      createdAt: '8 月 5 日 09:18',
    })
  }

  if (['running', 'succeeded', 'failed'].includes(status)) {
    events.push({
      id: `${taskId}-event-running`,
      type: 'started',
      title: '开始执行',
      description: 'Agent 已读取相关文件并启动实现与验证流程。',
      createdAt: '8 月 5 日 09:26',
    })
  }

  if (status === 'running') {
    events.push({
      id: `${taskId}-event-checkpoint`,
      type: 'checkpoint',
      title: '完成阶段检查点',
      description: '核心实现已完成，正在补充测试并整理变更摘要。',
      createdAt: updatedAt,
    })
  }

  if (status === 'succeeded' || status === 'failed' || status === 'cancelled') {
    events.push({
      id: `${taskId}-event-${status}`,
      type: status === 'succeeded' ? 'completed' : status === 'failed' ? 'failed' : 'cancelled',
      title: status === 'succeeded' ? '执行完成' : status === 'failed' ? '执行中断' : '任务已取消',
      description: status === 'succeeded' ? '结果与文件变更已生成，等待审查。' : status === 'failed' ? '运行时返回错误，建议检查连接与凭证。' : '执行资源已释放。',
      createdAt: updatedAt,
    })
  }

  return events
}

